"""Local acceptance with temporary stores and a synthetic owned desktop window."""
import json
from pathlib import Path
import tempfile
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import time

from karen_core2.runtime import CoreRuntime


def main():
    started = time.monotonic()
    with tempfile.TemporaryDirectory(prefix='karen-core2-live-') as temporary:
        root = Path(temporary)
        runtime = CoreRuntime(archive_path=root / 'core.sqlite3', task_path=root / 'tasks.sqlite3')
        catalog = runtime.models.discover(force=True)
        assert catalog and all('cloud' not in item['name'] for item in catalog)
        print('Installed local capabilities verified:', len(catalog), flush=True)
        plan = runtime.create_plan('Diagnostica mi PC')
        result = runtime.run(plan['id'])
        assert result['status'] == 'completed', runtime.render(result)
        assert all(item['status'] == 'completed' for item in result['steps'])
        assert all(item['attempts'] == 1 for item in result['steps'])
        runtime.memory.record_procedure(result)
        assert runtime.memory.retrieve('Karen', 'diagnostica', confirmed_only=True)[0]['kind'] == 'procedural'
        print('Real measured and verified plan:', len(result['steps']), 'steps; procedural memory OK', flush=True)
        # Exercise structured model planning without executing its proposed file action.
        generated = runtime.create_plan('Lista los archivos de la carpeta C:/karen con la herramienta de lectura admin_files. No hagas cambios.')
        assert generated['steps'] and all(s['permission'] == 'read' for s in generated['steps'])
        print('Structured plan generated by installed local model: OK', flush=True)
        answer = runtime.chat('Saluda en una sola frase.', preferred='gemma3:1b')
        assert answer.strip()
        print('Local conversation generated: OK', flush=True)
        # Capture only the synthetic window owned by this verifier; no user window pixels.
        import tkinter as tk
        from PIL import ImageGrab
        import ctypes
        from ctypes import wintypes
        window = tk.Tk()
        window.title('Karen Core 2 · prueba de percepción local')
        window.geometry('720x320+30+30')
        window.configure(bg='white')
        tk.Label(window, text='KAREN LOCAL TEST', font=('Segoe UI', 18), bg='white', fg='black').pack(pady=(25, 12))
        tk.Label(window, text='ERROR 503', font=('Segoe UI', 48, 'bold'), bg='white', fg='black').pack(pady=15)
        tk.Label(window, text='Synthetic window. No private user data.', font=('Segoe UI', 14), bg='white', fg='black').pack()
        window.attributes('-topmost', True)
        window.update()
        bbox = (window.winfo_rootx(), window.winfo_rooty(), window.winfo_rootx() + window.winfo_width(), window.winfo_rooty() + window.winfo_height())
        try:
            image = ImageGrab.grab(bbox=bbox, all_screens=True)
            user = ctypes.WinDLL('user32'); user.GetForegroundWindow.restype = wintypes.HWND
            target = {'hwnd': int(user.GetForegroundWindow() or 0), 'bbox': bbox}
        finally:
            window.destroy()
        runtime.vision._capture = lambda scope: (image.copy(), target)
        runtime.vision.pause(False)
        try:
            visual = runtime.vision.analyze('Lee el código de error grande en esta ventana. Responde solo con el código.')
            assert '503' in visual['analysis'], 'El modelo no reconoció el código sintético: ' + visual['analysis']
        finally:
            runtime.vision.pause()
        assert runtime.models.endpoint == 'http://127.0.0.1:11434'
        report = {'local_models': [item['name'] for item in catalog], 'verified_steps': len(result['steps']),
                  'structured_planning': True, 'procedural_memory': True, 'local_conversation': True,
                  'desktop_vision_error_code': '503', 'vision_model': runtime.models.metrics[-1]['model'],
                  'new_models_downloaded': 0, 'cloud_requests': 0,
                  'latency': runtime.models.metrics, 'duration_seconds': round(time.monotonic() - started, 2)}
        output = Path('C:/karen/.private/core2-live-acceptance.json')
        output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
        print(json.dumps(report, ensure_ascii=True), flush=True)


if __name__ == '__main__':
    main()
